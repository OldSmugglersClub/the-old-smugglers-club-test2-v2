import assert from 'node:assert/strict';
import {readPortugalMatchHeader,reconcile,SOURCES} from './offizielle-quellen-test23-quellenstatus.mjs';
const src=SOURCES.portugal;
const head='SL Benfica D V V V dom. 27 dez -- -- Sporting CP';
assert.equal(readPortugalMatchHeader(head,src).status,'DATUM_BESTAETIGT_ANSTOSS_OFFEN');
assert.equal(readPortugalMatchHeader(head,src).anstoss,null);
assert.equal(readPortugalMatchHeader(head.replace('-- --','20h30'),src).status,'OFFIZIELLER_SPIELKOPF_MIT_VOLLSTAENDIGEM_TERMIN');
assert.equal(readPortugalMatchHeader(head.replace('-- --','20h30'),src).anstoss,'21:30');
assert.equal(readPortugalMatchHeader(head.replace('-- --','21:15'),src).anstoss,'22:15');
assert.equal(readPortugalMatchHeader(head.replace('-- --','25:15'),src).status,'ANSTOSS_UNGUELTIG');
assert.equal(readPortugalMatchHeader('SL Benfica ... 27 dez 20h30 Sporting CP',src).status,'DATUM_NICHT_EINDEUTIG');
assert.equal(readPortugalMatchHeader('SL Benfica dom. 27 dez 20h30 Porto',src).status,'PAARUNG_NICHT_EINDEUTIG');
assert.equal(readPortugalMatchHeader('SL Benfica dom. 27 dez 20h30 Sporting CP', {...src,url:'https://evil.example/match'}).status,'SPIELURL_NICHT_VERIFIZIERT');
const games=[{id:'wr-2026-27-02',datum:'2026-12-27',anstoss:'18:00'},{id:'pk-2026-27-05-le-classique',datum:'2027-02-07',anstoss:'20:45'}];
const sonder={automaticModification:false,findings:games.map(x=>({spielId:x.id,status:'NICHT_EINDEUTIG_AUSLESBAR'}))};
const browser={automatischeAenderung:false,befunde:games.map(x=>({spielId:x.id,status:'KEIN_EINDEUTIGES_SPIEL'}))};
const rep=reconcile({games,sonder,browser,portugalPage:head});
assert.equal(rep.spiele.length,2);
assert.equal(rep.spiele[0].status,'ANSTOSS_OFFEN_WEITER_UEBERWACHEN');
assert.equal(rep.spiele[0].moeglicherNeuerTermin,null);
assert.equal(rep.spiele[1].status,'WEITER_UEBERWACHEN');
assert.equal(rep.automatischeAenderung,false);
const future=reconcile({games,sonder,browser,portugalPage:head.replace('-- --','20h30')});
assert.deepEqual(future.spiele[0].moeglicherNeuerTermin,{datum:'2026-12-27',anstoss:'21:30'});
assert.equal(future.spiele[0].korrekturFreigabe,false);
assert.throws(()=>reconcile({games:games.slice(0,1),sonder,browser,portugalPage:head}),/UEBERWACHUNG_LUECKE/);
assert.throws(()=>reconcile({games,sonder:{...sonder,automaticModification:true},browser,portugalPage:head}),/QUELLENBERICHT_UNGUELTIG/);
console.log('TEST23: 16 Quellensicherheits- und Statusprüfungen bestanden.');
